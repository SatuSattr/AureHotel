CREATE TABLE IF NOT EXISTS `bookings` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `reference` VARCHAR(32) NOT NULL,
    `hash_id` CHAR(32) NOT NULL,
    `guest_name` VARCHAR(120) NOT NULL,
    `gender` ENUM('male', 'female') NOT NULL,
    `guest_origin` ENUM('local', 'international') NOT NULL DEFAULT 'local',
    `nationality` CHAR(2) NOT NULL DEFAULT 'ID',
    `email` VARCHAR(190) NOT NULL,
    `phone` VARCHAR(30) NOT NULL,
    `identity_number` VARCHAR(25) NOT NULL,
    `room_id` VARCHAR(40) NOT NULL,
    `room_name` VARCHAR(120) NOT NULL,
    `booking_date` DATE NOT NULL,
    `nights` TINYINT UNSIGNED NOT NULL,
    `breakfast` TINYINT(1) NOT NULL DEFAULT 0,
    `room_price` INT UNSIGNED NOT NULL,
    `room_subtotal` INT UNSIGNED NOT NULL,
    `discount` INT UNSIGNED NOT NULL DEFAULT 0,
    `breakfast_total` INT UNSIGNED NOT NULL DEFAULT 0,
    `total` INT UNSIGNED NOT NULL,
    `currency` CHAR(3) NOT NULL DEFAULT 'IDR',
    `status` ENUM('paid') NOT NULL DEFAULT 'paid',
    `ip_address` VARCHAR(45) NOT NULL,
    `user_agent` VARCHAR(255) NOT NULL DEFAULT '',
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uniq_bookings_reference` (`reference`),
    UNIQUE KEY `uniq_bookings_hash_id` (`hash_id`),
    KEY `idx_bookings_email` (`email`),
    KEY `idx_bookings_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
